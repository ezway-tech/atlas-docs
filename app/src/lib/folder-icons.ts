export type FolderIconId=(typeof FOLDER_ICONS)[number]['id'];
const IDS=new Set<string>(FOLDER_ICONS.map(x=>x.id));
export function folderIconId(value:unknown):FolderIconId|null{return typeof value==='string'&&IDS.has(value)?value as FolderIconId:null;}
const fold=(s:string)=>s.toLocaleLowerCase('vi').normalize('NFD').replace(/\p{M}/gu,'');
export function matchFolderIcons(query:string){const q=fold(query.trim());return FOLDER_ICONS.filter(x=>!q||fold(x.id+' '+x.q).includes(q));}
