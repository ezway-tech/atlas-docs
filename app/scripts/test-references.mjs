import assert from 'node:assert/strict';
import {mkdtemp,mkdir,readFile,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {randomUUID} from 'node:crypto';
import {loadTs} from './load-ts.mjs';

const root=await mkdtemp(path.join(tmpdir(),'atlas-refs-'));
process.env.DATA_DIR=root;
const id=()=>randomUUID();
try{
 const boot=spawnSync(process.execPath,['scripts/bootstrap.mjs'],{cwd:process.cwd(),env:{...process.env,DATA_DIR:root},encoding:'utf8'});
 assert.equal(boot.status,0,boot.stderr);
 const current=id(),historyOnly=id(),loose=id(),extra=id(),gone=id();
 const store=await loadTs('src/lib/store.ts');
 const refs=await loadTs('src/lib/asset-references.ts');
 await store.createFolder('','Topic',null);
 await store.createDoc('topic','Note');
 await store.saveDoc('topic/note','---\ntitle: "Note"\n---\n\n![a](/api/media/'+current+')\n');
 const revDir=path.join(root,'history','topic','note');
 const rev='2026-01-01T00-00-00-000Z_'+id()+'.md';
 await mkdir(revDir,{recursive:true});
 await writeFile(path.join(revDir,rev),'![old](/api/media/'+historyOnly+')\n');
 await writeFile(path.join(revDir,rev.replace(/\.md$/,'.json')),'{}');
 const asset=(assetId,name)=>({id:assetId,filename:name,storedName:assetId+'.bin',mimeType:'application/octet-stream',size:4,alt:'',source:'upload',createdAt:new Date().toISOString()});
 await store.writeDB(data=>{data.assets.push(asset(current,'current.bin'),asset(historyOnly,'history.bin'),asset(loose,'loose.bin'),asset(extra,'extra.bin'),asset(gone,'gone.bin'));});
 await mkdir(path.join(root,'uploads'),{recursive:true});
 for(const item of [current,historyOnly,loose,extra])await writeFile(path.join(root,'uploads',item+'.bin'),'data');
 const scan=await refs.scanCleanup();
 const by=Object.fromEntries(scan.candidates.map(item=>[item.filename,item.group]));
 assert.equal(by['current.bin'],undefined);
 assert.equal(by['history.bin'],'history');
 assert.equal(by['loose.bin'],'unreferenced');
 assert.ok(scan.missing.some(item=>item.id===gone));
 const looseId=scan.candidates.find(item=>item.filename==='loose.bin').id;
 const extraId=scan.candidates.find(item=>item.filename==='extra.bin').id;
 const historyId=scan.candidates.find(item=>item.filename==='history.bin').id;
 await rm(path.join(root,'uploads',extra+'.bin'));
 await store.saveDoc('topic/note','---\ntitle: "Note"\n---\n\n![a](/api/media/'+current+')\n![b](/api/media/'+loose+')\n');
 const partial=await refs.applyCleanup(scan.scannedAt,[historyId,looseId,extraId]);
 assert.ok(partial.skipped.some(item=>item.id===historyId&&item.reason.includes('lịch sử')));
 assert.ok(partial.skipped.some(item=>item.id===looseId));
 assert.ok(partial.failed.some(item=>item.id===extraId));
 assert.equal(partial.deleted.includes(looseId),false);
 assert.equal(partial.freedBytes,0);
 assert.equal(await readFile(path.join(root,'uploads',historyOnly+'.bin'),'utf8'),'data');
 const free=id();
 await store.writeDB(data=>{data.assets.push(asset(free,'free.bin'));});
 await writeFile(path.join(root,'uploads',free+'.bin'),'data');
 const again=await refs.scanCleanup();
 const freeId=again.candidates.find(item=>item.filename==='free.bin').id;
 const removed=await refs.applyCleanup(again.scannedAt,[freeId]);
 assert.deepEqual(removed.deleted,[freeId]);
 assert.equal(removed.freedBytes,4);
 assert.equal((await readFile(path.join(revDir,rev),'utf8')).includes(historyOnly),true);
 const unknownId=id();
 await store.writeDB(data=>{data.assets.push(asset(unknownId,'unknown.bin'));});
 await writeFile(path.join(root,'uploads',unknownId+'.bin'),'data');
 await store.saveDoc('topic/note','---\ntitle: "Note"\n---\n\n/api/media/not-a-real-id\n');
 const unsure=await refs.scanCleanup();
 assert.equal(unsure.uncertain,true);
 assert.equal(unsure.candidates.some(item=>item.group==='unreferenced'),false);
 console.log('PASS: asset references');
}finally{await rm(root,{recursive:true,force:true});}
