import '../helpers/environment.mjs';
import assert from 'node:assert/strict';
import {mkdtemp,readdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {loadTs} from '../helpers/load-ts.mjs';

const limits={maxUncompressedBytes:1024*1024*1024,maxZipBytes:1024*1024*1024,maxDataFiles:1000};
if(process.argv[2]==='import'){
 process.env.DATA_DIR=process.argv[3];
 const backup=await loadTs('src/lib/backup.ts');
 const result=await backup.importZip(process.argv[4],{deleteZip:false,limits});
 const names=(await readdir(path.join(process.argv[3],'history','topic','note'))).filter(name=>name.endsWith('.md'));
 assert.ok(names.length>=2,'import pruned history');
 assert.ok(result.historyOver.length,'over-limit history was not reported');
 console.log(JSON.stringify({ok:true,versions:names.length}));
 process.exit(0);
}
const root=await mkdtemp(path.join(tmpdir(),'atlas-history-'));
const restored=await mkdtemp(path.join(tmpdir(),'atlas-history-restore-'));
process.env.DATA_DIR=root;
const boot=(dir)=>{const result=spawnSync(process.execPath,['../scripts/setup/bootstrap.mjs'],{cwd:process.cwd(),env:{...process.env,DATA_DIR:dir},encoding:'utf8'});assert.equal(result.status,0,result.stderr);};
boot(root);boot(restored);
try{
 const policy=await loadTs('src/lib/history-policy.ts');
 const kept=policy.selectHistoryPrune([{name:'new',size:80},{name:'old',size:80}],{maxCount:2,maxBytes:50},'old');
 assert.deepEqual(kept.remove,['new']);
 assert.equal(kept.remove.includes('old'),false);
 assert.ok(kept.overBytes>0);
 const store=await loadTs('src/lib/store.ts');
 const extras=await loadTs('src/lib/extras.ts');
 const backup=await loadTs('src/lib/backup.ts');
 await store.writeDB(data=>{data.settings.history={maxCount:2,maxBytes:10*1024*1024};});
 await store.createFolder('','Topic',null);
 await store.createDoc('topic','Note');
 const doc='topic/note';
 const body=(text)=>'---\ntitle: "Note"\n---\n\n# '+text+'\n';
 const dir=path.join(root,'history','topic','note');
 const count=async()=>(await readdir(dir)).filter(name=>name.endsWith('.md')).length;
 await store.saveDoc(doc,body('same'));
 const first=await count();
 await store.saveDoc(doc,body('same'));
 assert.equal(await count(),first);
 await store.saveDoc(doc,body('b'));
 await store.saveDoc(doc,body('c'));
 await store.saveDoc(doc,body('d'));
 assert.equal(await count(),2);
 for(const name of await readdir(dir))if(name.endsWith('.md'))assert.ok((await readdir(dir)).includes(name.replace(/\.md$/,'.json')));
 await store.writeDB(data=>{data.settings.history={maxCount:1,maxBytes:30};});
 const versions=await extras.history(doc);
 await store.saveDoc(doc,body('x'.repeat(80)),'restore');
 const protectedName=(await extras.history(doc))[0];
 assert.ok(protectedName);
 assert.notEqual(protectedName,versions.at(-1));
 const after=policy.selectHistoryPrune((await extras.history(doc)).map(name=>({name,size:200})),{maxCount:1,maxBytes:30},protectedName);
 assert.equal(after.remove.includes(protectedName),false);
 assert.ok(after.overBytes>0||after.overCount>0);
 assert.ok((await readdir(dir)).includes(protectedName));
 await store.writeDB(data=>{data.settings.history={maxCount:10,maxBytes:1024*1024};});
 await Promise.all([store.saveDoc(doc,body('parallel-a')),store.saveDoc(doc,body('parallel-b'))]);
 const finalRaw=(await store.getDoc(doc)).raw;
 assert.ok(finalRaw.includes('parallel-a')||finalRaw.includes('parallel-b'));
 await store.writeDB(data=>{data.settings.history={maxCount:1,maxBytes:10*1024*1024};});
 const exported=await backup.exportZip({limits});
 const importer=spawnSync(process.execPath,['--experimental-strip-types','../scripts/tests/app/test-history-policy.mjs','import',restored,exported.file],{cwd:process.cwd(),env:{...process.env,DATA_DIR:restored},encoding:'utf8'});
 assert.equal(importer.status,0,importer.stderr||importer.stdout);
 await exported.cleanup();
 const observed=await store.historyOverLimit();
 assert.equal(observed.docs.some(item=>item.id==='observed'||item.id.startsWith('observed/')),false);
 const preview=await store.historyOverLimit({maxCount:1,maxBytes:10*1024*1024});
 assert.ok(preview.docs.some(item=>item.remove>0&&item.removeBytes>0));
 await store.writeDB(data=>{data.settings={...data.settings,history:{maxCount:4,maxBytes:2048},backup:{maxUncompressedBytes:1024,maxZipBytes:2048,maxDataFiles:9}};});
 await store.writeDB(data=>{data.settings={...data.settings,history:{maxCount:7,maxBytes:4096}};});
 const afterHistory=await store.readDB();
 assert.equal(afterHistory.settings.history.maxCount,7);
 assert.equal(afterHistory.settings.backup.maxDataFiles,9);
 await store.writeDB(data=>{data.settings={...data.settings,backup:{...data.settings.backup,maxDataFiles:11}};});
 const afterBackup=await store.readDB();
 assert.equal(afterBackup.settings.history.maxCount,7);
 assert.equal(afterBackup.settings.backup.maxDataFiles,11);
 console.log('PASS: history policy');
}finally{await rm(root,{recursive:true,force:true});await rm(restored,{recursive:true,force:true});}
